#!/usr/bin/env python3
"""Check prompts/prompts.json against the brief (pushpop_manga_brief.txt, 23.11.2026) before any credits.
Exits non-zero if any check fails. Writes prompts/QA.md."""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(HERE, "..", "prompts")
doc = json.load(open(os.path.join(P, "prompts.json"), encoding="utf-8"))
B, panels = doc["blocks"], doc["panels"]
ASPECTS = {"auto", "1:1", "3:2", "2:3", "4:3", "3:4", "16:9", "9:16", "21:9", "27:16", "16:27", "9:8", "8:9", "4:5", "5:4"}

# brief section 2: panel -> sound effect
BRIEF_SFX = {"A1": None, "A2": "ザッ", "A3": "ドン!!", "A4": "ズザッ", "A5": "ゴゴゴ",
             "B1": None, "B2": None, "B3": None, "B4": None}
# brief section 3: the only places red may appear (the scene text must say which red it is)
RED_OK = {"A2": "frame", "A3": "energy", "A4": "energy", "A5": "cushion"}
SAMURAI_IN = {"A1", "A2", "A3", "A4", "B1", "B2", "B3", "B4"}
PRODUCT_IN = {"A5", "B1", "B2", "B3", "B4"}
SHRINE_IN = {"A3", "A4", "B1", "B2", "B3", "B4"}  # A5 is a close-up inside the chest
# brief section 2, side B steps
STEP_WORDS = {"B1": ["vial out", "lid is still"], "B2": ["lifts the round clear", "salmon"],
              "B3": ["pouring", "teriyaki"], "B4": ["pushes the", "bite"]}

fails, rows = [], []


def check(cond, pid, msg):
    if not cond:
        fails.append(f"{pid}: {msg}")
    return "ok" if cond else "FAIL"


assert len(panels) == 9, "need 9 panels"
for p in panels:
    pid, prm = p["id"], p["params"]
    t = prm["prompt"]
    scene = [l for l in t.split("\n") if l.startswith(f"PANEL {pid}")][0]
    r = []
    for b in p["blocks"]:
        r.append(check(B[b] in t, pid, f"block {b} not verbatim"))
    check("NO_TEXT" in p["blocks"], pid, "NO_TEXT block missing")
    check(not re.search(r"\bsoy\b", t, re.I), pid, "says soy (brief: teriyaki)")
    check(("CHARACTER" in p["blocks"]) == (pid in SAMURAI_IN), pid, "CHARACTER block mismatch")
    check(("PRODUCT" in p["blocks"]) == (pid in PRODUCT_IN), pid, "PRODUCT block mismatch")
    check(("SHRINE" in p["blocks"]) == (pid in SHRINE_IN), pid, "SHRINE block mismatch")
    check(p["sfx"] == BRIEF_SFX[pid], pid, f"sfx {p['sfx']} != brief {BRIEF_SFX[pid]}")
    check(prm["aspect_ratio"] in ASPECTS, pid, "aspect not supported by gpt_image_2_6")
    check(prm["model"] == "gpt_image_2_6", pid, "model is not GPT Image 2.6")
    ids = [m["value"] for m in prm["medias"]]
    check(set(ids) <= set(doc["refs"].values()), pid, "unknown reference id")
    check(("2b2fa7d5-f56b-4455-8c2e-0513f307d93a" in ids) == (pid == "A2"), pid, "entrance ref only in A2")
    check(doc["refs"]["samurai"] in ids, pid, "samurai reference missing")
    reds = re.findall(r"\bred\b", scene, re.I)
    if pid in RED_OK:
        check(RED_OK[pid] in scene, pid, f"red must be the {RED_OK[pid]}")
    else:
        check(not reds or "No red" in scene, pid, "red appears where the brief allows none")
    check("gold" not in scene.lower().replace("no gold", ""), pid, "gold in scene text (gold is only the label rim, via PRODUCT)")
    for w in STEP_WORDS.get(pid, []):
        check(w in scene, pid, f"step action missing: {w}")
    if p["sfx"]:
        check("lettering added later" in scene, pid, "no empty area reserved for the sound effect")
    if p["side"] == "B":
        check("top-right corner" in scene, pid, "no empty corner for the number seal")
    rows.append(f"| {pid} | {p['name']} | {p['sfx'] or '-'} | {prm['aspect_ratio']} | "
                f"{', '.join(p['refs'])} | {len(t)} | {'FAIL' if any(f.startswith(pid + ':') for f in fails) else 'ok'} |")

cost = 0.75 * len(panels)
md = ["# Prompt QA against the brief (auto-generated by scripts/check_prompts.py)", "",
      "| Panel | What | Sound | Aspect | References | Prompt chars | Checks |", "|---|---|---|---|---|---|---|", *rows, "",
      f"Model: GPT Image 2.6, low, 1k. Expected cost: 9 x 0.75 = {cost:.2f} credits (confirm with estimate_image_cost).", "",
      "Checks per panel: every fixed block verbatim + NO_TEXT; no 'soy'; samurai/product/shrine blocks exactly where the",
      "brief puts them; sound effect = brief section 2; red only for gate frame / energy wave / cushion; gold only via the",
      "label rim; entrance reference only in A2; each how-to step shows its action; empty space kept for sounds and seals.", ""]
if fails:
    md += ["## Failures", *[f"- {f}" for f in fails]]
open(os.path.join(P, "QA.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
print("\n".join(rows))
print(f"{len(fails)} failures" + ("" if not fails else ":\n" + "\n".join(fails)))
sys.exit(1 if fails else 0)
