"""Traces the gold Yoko Ono logo out of shared/logo-source.png (a crop of the restaurant's own artwork)
into shared/logo-path.js, a single filled SVG path used by shared/logo.js.
Needs numpy, pillow and potracer:  python trace-logo.py
"""
import os

import numpy as np
import potrace
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
UP = 4  # trace at 4x for smooth curves; coordinates are written back at 1x

img = Image.open(os.path.join(HERE, "logo-source.png")).convert("RGB")
a = np.asarray(img).astype(float)
r, g, b = a[..., 0], a[..., 1], a[..., 2]
# Gold: bright, yellow-orange, clearly warmer than blue but not as red as the sunset behind it
gold = (r > 140) & (g > 105) & (r - g < 80) & (r - g > 0) & (g - b > 30)

# Keep the logo, drop the scenery: the frame column, plus the name band, which runs wider
h, w = gold.shape
keep = np.zeros_like(gold)
keep[:, 160:600] = True          # frame and everything inside it
keep[360:475, 15:775] = True      # "YOKO ONO", wider than the frame
keep[490:530, 218:545] = False    # "ASIAN KITCHEN" is too thin to trace; it is typeset instead
gold &= keep

# Smooth at 4x before tracing
m = Image.fromarray((gold * 255).astype("uint8")).resize((w * UP, h * UP), Image.BICUBIC).filter(ImageFilter.GaussianBlur(UP * 0.6))
bits = np.asarray(m) > 127

# potracer fills the False pixels, so hand it the inverse
paths = potrace.Bitmap(~bits).trace(turdsize=60 * UP * UP, alphamax=1.0, opticurve=True, opttolerance=0.2)


def fmt(p):
    return f"{p.x / UP:.1f} {p.y / UP:.1f}"


d = []
for curve in paths:
    d.append("M" + fmt(curve.start_point))
    for seg in curve.segments:
        if seg.is_corner:
            d.append("L" + fmt(seg.c) + "L" + fmt(seg.end_point))
        else:
            d.append("C" + fmt(seg.c1) + " " + fmt(seg.c2) + " " + fmt(seg.end_point))
    d.append("Z")

ys, xs = np.nonzero(gold)
box = (int(xs.min()) - 4, int(ys.min()) - 4, int(xs.max() - xs.min()) + 8, int(ys.max() - ys.min()) + 8)
with open(os.path.join(HERE, "logo-path.js"), "w") as f:
    f.write("// Generated by trace-logo.py from logo-source.png. Do not edit by hand.\n")
    f.write(f'window.LOGO_PATH = {{ viewBox: "{box[0]} {box[1]} {box[2]} {box[3]}", d: "{"".join(d)}" }};\n')
print("curves", len(paths), "viewBox", box, "chars", sum(map(len, d)))
